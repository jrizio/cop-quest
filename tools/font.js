const ROWS = 9;

function glyph(ch) { return G[ch] || G["?"]; }
function measure(text) { let w = 0; for (const ch of text) w += glyph(ch)[0].length + 1; return Math.max(0, w - 1); }

// Stamp text into a Painter at (x, y) = top-left of the cap height.
function stamp(p, text, x, y, color, scale = 1, alpha = 1) {
	let cx = x;
	for (const ch of text) {
		const g = glyph(ch);
		for (let r = 0; r < g.length; r++) for (let c = 0; c < g[r].length; c++)
			if (g[r][c] === "#") p.rect(cx + c * scale, y + r * scale, scale, scale, color, alpha);
		cx += (g[0].length + 1) * scale;
	}
	return cx - x;
}

